# ============================================================
# 地支六沖：對宮相沖
#   子午、丑未、寅申、卯酉、辰戌、巳亥
# ============================================================
LIUCHONG_PAIRS = [
    frozenset({"子", "午"}),
    frozenset({"丑", "未"}),
    frozenset({"寅", "申"}),
    frozenset({"卯", "酉"}),
    frozenset({"辰", "戌"}),
    frozenset({"巳", "亥"}),
]


def branch_relation(a, b):
    """
    判斷兩地支的合沖關係(地支兩兩之間,不是卦的格局)。
    回傳 "相合" / "相沖" / "" (無)
    a==b 時回傳 ""(同支不是合也不是沖)

    注意:六爻學裡「六沖卦/六合卦」是整盤卦的格局,
    跟此處的地支對沖/對合不同,不應混用。
    """
    if a == b:
        return ""
    pair = frozenset({a, b})
    if pair in LIUHE_PAIRS:
        return "相合"
    if pair in LIUCHONG_PAIRS:
        return "相沖"
    return ""


