# ============================================================
# 地支三合:四組,每組三個地支合成一個五行局
#   申子辰合水、寅午戌合火、巳酉丑合金、亥卯未合木
# ============================================================
SANHE_GROUPS = [
    frozenset({"申", "子", "辰"}),  # 水局
    frozenset({"寅", "午", "戌"}),  # 火局
    frozenset({"巳", "酉", "丑"}),  # 金局
    frozenset({"亥", "卯", "未"}),  # 木局
]


def is_sanhe(branch_a, branch_b):
    """判斷兩個地支是否同屬一個三合圈"""
    if branch_a == branch_b:
        return False
    for group in SANHE_GROUPS:
        if branch_a in group and branch_b in group:
            return True
    return False
