def gua_type(gua_name):
    """
    判斷卦名是「六沖卦」、「六合卦」、還是「一般」。
    回傳:"六沖卦" / "六合卦" / ""
    """
    if gua_name in LIUCHONG_GUA:
        return "六沖卦"
    if gua_name in LIUHE_GUA:
        return "六合卦"
    return ""


