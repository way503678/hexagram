HEXAGRAMS = {}

for palace in PALACE_ORDER:
    for (upper, lower), bian in _gen_palace(palace):
        key = (upper, lower)
        if key in HEXAGRAMS:
            continue
        shi, ying = BIAN_SHIYING[bian]
        name = NAME_TABLE[key]
        text = TEXT_TABLE[name]
        branches, stems = build_najia(upper, lower)
        HEXAGRAMS[key] = {
            "卦名": name,
            "卦辭": text,
            "卦宮": palace,
            "卦宮五行": TRIGRAM_ELEMENT[palace],
            "卦變": bian,
            "世爻": shi,
            "應爻": ying,
            "納甲": branches,
            "納甲天干": stems,
        }


def get_hexagram_info(upper, lower):
    return HEXAGRAMS.get((upper, lower))


