def _gen_palace(root):
    """依京房八宮卦變規則生成一宮 8 卦"""
    base = TRIGRAM_LINES[root] + TRIGRAM_LINES[root]

    def flip(lines, *idxs):
        out = lines[:]
        for i in idxs:
            out[i] = 1 - out[i]
        return out

    def to_key(lines):
        lower = tuple(lines[0:3])
        upper = tuple(lines[3:6])
        return LINES_TO_TRIGRAM[upper], LINES_TO_TRIGRAM[lower]

    results = []
    results.append((to_key(base), "純卦"))
    s1 = flip(base, 0);   results.append((to_key(s1), "一世"))
    s2 = flip(s1, 1);     results.append((to_key(s2), "二世"))
    s3 = flip(s2, 2);     results.append((to_key(s3), "三世"))
    s4 = flip(s3, 3);     results.append((to_key(s4), "四世"))
    s5 = flip(s4, 4);     results.append((to_key(s5), "五世"))
    s_you = flip(s5, 3);  results.append((to_key(s_you), "遊魂"))
    s_gui = s_you[:]
    s_gui[0:3] = TRIGRAM_LINES[root]
    results.append((to_key(s_gui), "歸魂"))

    return [((u, l), bian) for (u, l), bian in results]


