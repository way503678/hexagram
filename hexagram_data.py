def build_najia(upper, lower):
    """依上下卦組出六爻納甲（由下而上）：回傳 [地支 list, 天干 list]"""
    branches = INNER_NAJIA[lower] + OUTER_NAJIA[upper]
    inner_stem = TRIGRAM_STEM[lower][0]
    outer_stem = TRIGRAM_STEM[upper][1]
    stems = [inner_stem] * 3 + [outer_stem] * 3
    return branches, stems


